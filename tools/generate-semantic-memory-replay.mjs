#!/usr/bin/env node
// Source-only adapter: no network, model, perception or generated golden answers.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { cases } from './fixtures/home-awareness.mjs';

const root = new URL('../', import.meta.url);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const homePath = 'tools/fixtures/home-awareness.mjs';
const topologyPath = 'maps/center.example.json';
const mapPath = 'maps/community/oas-apartment.blindplace.json';
const sourceHashes = Object.fromEntries(await Promise.all([homePath, topologyPath, mapPath].map(async path =>
  [path, hash(await readFile(new URL(path, root)))])));
const selected = ['enter', 'bedroom', 'bathroom-arrival', 'goal-change'];
const scenarios = selected.map(id => {
  const item = cases.find(item => item.id === id);
  if (!item) throw new Error(`Missing authored fixture ${id}`);
  const { places, entities, goal, conversation } = item.request.context.situation;
  return { id, question: item.request.question, places, entities, goal, conversation };
});
const data = JSON.stringify({ sourceHashes, scenarios }, null, 2);
// Keep readable, original source data. Never feed captions back as detector labels.
const output = `// Generated by tools/generate-semantic-memory-replay.mjs. Do not hand-edit.\n// Authored fictional inputs, not recorded sensors, model answers or personal data.\nimport Foundation\n\nenum SemanticMemoryReplayFixture {\n    static let data = Data(#"""\n${data}\n"""#.utf8)\n}\n`;
const target = new URL('BlindCore/Tests/BlindCoreTests/SemanticMemoryReplayFixture.swift', root);
if (process.argv.includes('--write')) {
  await writeFile(target, output);
} else {
  if (await readFile(target, 'utf8') !== output) throw new Error('Fixture drift: run node tools/generate-semantic-memory-replay.mjs --write');
}
console.log(JSON.stringify({ status: 'verified', generatedFile: fileURLToPath(target), sourceHashes,
  scenarios: scenarios.length, sourceEntities: scenarios.reduce((sum, item) => sum + item.entities.length, 0),
  generatedSHA256: hash(output), limitations: 'Authored records only; no perception, model or live localization execution.' }, null, 2));
